"""Generate resources/commands.md from the extension's package.json at the pinned release.

The tables (commands and where they appear, views, the debugger's launch attributes, the config
schema, defaults the extension sets) come straight from `contributes` in package.json, so command
IDs and titles are never paraphrased.

Usage:
  python3 scripts/gen_reference.py                 # fetch package.json at the pinned tag, write
  python3 scripts/gen_reference.py --check         # exit 1 if commands.md is out of date
  python3 scripts/gen_reference.py --package-json PATH   # use a local copy instead of fetching
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
OUT = SKILL / "resources" / "commands.md"
REPO = "cqframework/vscode-cql"
REF = "v1.0.0"
SOURCE_ID = "VSCQL-1.0.0"
URL = f"https://raw.githubusercontent.com/{REPO}/{REF}/package.json"

# Where a menu contribution puts a command, in words.
MENU_PLACES = {
    "editor/context": "editor right-click",
    "cql.editor.submenu.executeCql": "editor right-click → Execute CQL",
    "cql.editor.submenu.viewElm": "editor right-click → View ELM",
    "view/title": "view toolbar",
    "view/item/context": "tree item",
    "editor/title": "editor title bar",
    "editor/title/run": "editor title bar (run)",
}


def load(path: str | None) -> str:
    """The raw text of package.json (the line count is part of the citation)."""
    if path:
        return Path(path).read_text(encoding="utf-8")
    req = urllib.request.Request(URL, headers={"User-Agent": "cqf-skills-gen-reference"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def view_names(c: dict) -> dict[str, str]:
    return {v["id"]: v["name"] for group in c.get("views", {}).values() for v in group}


def where(cmd: str, c: dict) -> tuple[bool, list[str]]:
    """(shown in the Command Palette?, other places it appears)."""
    menus = c.get("menus", {})
    palette = True
    for m in menus.get("commandPalette", []):
        if m.get("command") == cmd and m.get("when", "").strip() == "false":
            palette = False
    views = view_names(c)
    places: list[str] = []
    for menu, items in menus.items():
        if menu == "commandPalette":
            continue
        for m in items:
            if m.get("command") != cmd:
                continue
            place = MENU_PLACES.get(menu, menu)
            if menu.startswith("view/"):
                view = next((v for v in views if f"view == {v}" in m.get("when", "")), None)
                if view:
                    place = f"{views[view]} {place}"
            if place not in places:
                places.append(place)
    return palette, places


def render(pkg: dict, nlines: int | None = None) -> str:
    c = pkg["contributes"]
    loc = f"package.json:1-{nlines}" if nlines else "package.json:1"
    deps = pkg.get("javaDependencies", {})
    L = [
        "# Commands, Views and Contributed Settings",
        "",
        f"Baseline: vscode-cql {pkg['version']}. Untagged statements hold at this version only.",
        f"Sources: {SOURCE_ID}",
        "",
        f"Generated by `scripts/gen_reference.py` from `package.json` at `{REF}` "
        f"[src: {SOURCE_ID} {loc}]. Don't edit by hand.",
        "",
        "## The extension",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| Extension ID | `{pkg['publisher']}.{pkg['name']}` |",
        f"| Version | {pkg['version']} |",
        f"| VS Code | `{pkg['engines']['vscode']}` |",
        f"| Activates on | {', '.join('`' + e + '`' for e in pkg.get('activationEvents', []))} |",
    ]
    for name, d in deps.items():
        L.append(f"| Language server | `{d['groupId']}:{d['artifactId']}:{d['version']}` ({name}) |")
    L.append(f"| VS Code settings contributed | {'none' if 'configuration' not in c else 'see below'} |")

    L += ["", "## Commands", "",
          "Titles as VS Code shows them (category prefix in the Command Palette). \"Palette\" is whether the "
          "command can be run from the Command Palette. \"No menu\" means no menu in `package.json` names it: "
          "it can only be run by a tree item's click action, by another command, or not from the UI at all.",
          "", "| Title | Command ID | Palette | Also in |", "| --- | --- | --- | --- |"]
    for cmd in c.get("commands", []):
        palette, places = where(cmd["command"], c)
        title = (cmd.get("category") + ": " if cmd.get("category") else "") + cmd["title"]
        also = ", ".join(places) or ("" if palette else "no menu")
        L.append(f"| {esc(title)} | `{cmd['command']}` | {'yes' if palette else 'no'} | {esc(also)} |")

    L += ["", "## Views", "", "| View | ID | Container | Shown when |", "| --- | --- | --- | --- |"]
    for container, views in c.get("views", {}).items():
        for v in views:
            L.append(f"| {esc(v['name'])} | `{v['id']}` | {container} | {('`' + v['when'] + '`') if v.get('when') else 'always'} |")

    for d in c.get("debuggers", []):
        launch = d.get("configurationAttributes", {}).get("launch", {})
        required = set(launch.get("required", []))
        L += ["", f"## Debugger: type `{d['type']}`", "",
              f"`launch.json` attributes for `\"type\": \"{d['type']}\", \"request\": \"launch\"`:", "",
              "| Attribute | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |"]
        for k, v in launch.get("properties", {}).items():
            typ = v.get("type", "") + (f" ({' / '.join(v['enum'])})" if v.get("enum") else "")
            L.append(f"| `{k}` | {esc(typ)} | {'yes' if k in required else 'no'} | "
                     f"{('`' + str(v['default']) + '`') if 'default' in v else ''} | {esc(v.get('description', ''))} |")

    if c.get("jsonValidation"):
        L += ["", "## JSON schemas", "", "| Files | Schema |", "| --- | --- |"]
        for j in c["jsonValidation"]:
            L.append(f"| `{j['fileMatch']}` | `{j['url']}` |")
    if c.get("configurationDefaults"):
        L += ["", "## VS Code defaults the extension changes", "", "| Setting | Value |", "| --- | --- |"]
        for k, v in c["configurationDefaults"].items():
            L.append(f"| `{k}` | `{json.dumps(v)}` |")
    if c.get("languages"):
        L += ["", "## Languages", "", "| ID | Extensions | Aliases |", "| --- | --- | --- |"]
        for lang in c["languages"]:
            L.append(f"| `{lang['id']}` | {', '.join('`' + e + '`' for e in lang.get('extensions', []))} | "
                     f"{esc(', '.join(lang.get('aliases', [])))} |")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--package-json", help="local package.json (default: fetch at the pinned tag)")
    ap.add_argument("--check", action="store_true", help="exit 1 if commands.md differs")
    args = ap.parse_args(argv)
    raw = load(args.package_json)
    text = render(json.loads(raw), len(raw.splitlines()))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(SKILL)} is out of date; run scripts/gen_reference.py")
            return 1
        print("up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(SKILL)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
