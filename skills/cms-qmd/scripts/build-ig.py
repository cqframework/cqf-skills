#!/usr/bin/env python3
"""Regenerate the committed reference files from the CMS FHIR Quality Measure Development IG.

Usage:
    python build-ig.py [--source-dir DIR]

Without options, downloads the IG's narrative pages and shared CQL libraries from cqframework/cms-qmd
at the pinned commit below. With --source-dir, reads them from a local folder holding pages/*.md
and cql/*.cql instead, for offline use and tests.

Writes, under resources/:
- pages/       the IG's narrative pages, with publisher markup removed and links rewritten
- libraries/   the shared CQL libraries (CQMCommon, CQMConcepts, CQMElements, ClaimCommon, ...)

The IG declares its content CC0-1.0, and the repository is Apache-2.0. The IG isn't published to
packages.fhir.org; this pins its continuous build. The output is committed, so run this only when
you change the pin or this script. Requires Python 3.9+, no packages.
"""
from __future__ import annotations

import argparse
import html
import re
import sys
import urllib.request
from pathlib import Path

IG_VERSION = "0.8.0-cibuild"
IG_REPO = "cqframework/cms-qmd"
IG_COMMIT = "9bcc541e1ca4e12488fbca4e108727108be8c1aa"  # main, 2026-11-03
RAW = f"https://raw.githubusercontent.com/{IG_REPO}/{IG_COMMIT}/input/"
PUBLISHED = "https://build.fhir.org/ig/cqframework/cms-qmd/"

PAGES = [  # (file, title), in the IG's menu order
    ("index.md", "Home"),
    ("measure_guidance.md", "CMS Measure Authoring Guidance"),
    ("test_case_guidance.md", "CMS Test Case Guidance"),
    ("patterns.md", "Authoring Patterns"),
    ("pattern_fhir.md", "FHIR Patterns"),
    ("pattern_layers.md", "Logic Layers"),
    ("pattern_index.md", "Pattern Index"),
    ("pattern_patient.md", "Patient"),
    ("pattern_encounters.md", "Encounters"),
    ("pattern_observations.md", "Observations"),
    ("pattern_conditions.md", "Conditions"),
    ("pattern_medications.md", "Medications"),
    ("pattern_procedures.md", "Procedures"),
    ("pattern_devices.md", "Devices"),
    ("pattern_allergies.md", "Allergies"),
    ("pattern_immunizations.md", "Immunizations"),
    ("pattern_communication.md", "Communication"),
    ("pattern_claim.md", "Claim"),
    ("pattern_coverage.md", "Coverage"),
    ("pattern_billingrelated.md", "Billing-related Elements"),
    ("pattern_negation.md", "Negation Patterns"),
    ("usqc_update_process.md", "US Quality Core Update Process"),
    ("refactored_index.md", "Refactored Index"),
    ("knownissues.md", "Known Issues"),
    ("MADiE.md", "MADiE"),
    ("manifest_guidance.md", "CMS Manifest Guidance"),
    ("measure_profile.md", "Profiles Used by CMS Measures"),
    ("examples.md", "Examples"),
    ("change_control.md", "Change Control Process"),
    ("changes.md", "Change History"),
]
LIBRARIES = [
    "CQMCommon", "CQMConcepts", "CQMElements", "CQMInferences", "ClaimCommon", "ClaimElements",
    "MedicationCommon", "FHIRBuilders",
]

SKILL = Path(__file__).resolve().parent.parent
RES = SKILL / "resources"
ORIGIN = ("<!-- Generated by scripts/build-ig.py from {what} (IG content CC0-1.0, "
          "repository Apache-2.0). Do not edit. -->\n\n")


# --- Pages -------------------------------------------------------------------------------------

def inline_html(text: str) -> str:
    text = re.sub(r"<a\b[^>]*?href=\"([^\"]*)\"[^>]*>(.*?)</a>", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"</?(p|strong|em)>", lambda m: "**" if m.group(1) == "strong" else " ", text)
    text = re.sub(r"<code>(.*?)</code>", r"`\1`", text, flags=re.S)
    text = re.sub(r"<br\s*/?>", " ", text)
    text = re.sub(r"\s+", " ", text)
    return html.unescape(text).strip()


def html_table_to_markdown(table: str) -> str:
    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", table, flags=re.S)
    out = []
    for i, row in enumerate(rows):
        cells = re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", row, flags=re.S)
        cells = [inline_html(c).replace("|", "\\|") for c in cells]
        out.append("| " + " | ".join(cells) + " |")
        if i == 0:
            out.append("|" + " --- |" * len(cells))
    return "\n".join(out)


def clean_page(text: str) -> str:
    text = text.replace("\r\n", "\n")
    text = re.sub(r"\{%\s*include img[\w-]*\.html[^%]*%\}", "", text)
    text = re.sub(r"\{%\s*(?:include|lang-fragment) (\S+)\s*%\}",
                  lambda m: f"*(The published page has a generated table here: {m.group(1)}.)*",
                  text)
    text = re.sub(r"^\{:[^}]*\}\n?", "", text, flags=re.M)
    text = re.sub(r"<img [^>]*/?>", "", text)
    text = re.sub(r"<table[^>]*>.*?</table>",
                  lambda m: "\n\n" + html_table_to_markdown(m.group(0)) + "\n\n", text, flags=re.S)
    text = re.sub(r"[ \t]*<li>\s*(.*?)\s*</li>\s*", lambda m: "- " + inline_html(m.group(1)) + "\n",
                  text, flags=re.S)
    text = re.sub(r"[ \t]*</?ul>[ \t]*\n?", "", text)
    text = re.sub(r"<a\b[^>]*?href=\"([^\"]*)\"[^>]*>(.*?)</a>", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def rewrite_page_links(text: str, here: str, local: dict[str, str]) -> str:
    def repl(m):
        page, anchor = m.group(1), m.group(2) or ""
        suffix = f"#{anchor}" if anchor else ""
        if anchor and local.get(page) == here:
            return f"](#{anchor})"
        if page in local:
            return f"]({local[page]}{suffix})"
        return f"]({PUBLISHED}{page}{suffix})"
    return re.sub(r"\]\(([A-Za-z0-9_.-]+\.html)(?:#([^)\s]+))?\)", repl, text)


def build_pages(sources: dict[str, str]) -> dict[str, str]:
    local = {name.replace(".md", ".html"): name for name, _ in PAGES}
    local.update({f"Library-{lib}.html": f"../libraries/{lib}.cql" for lib in LIBRARIES})
    out = {}
    for name, title in PAGES:
        body = rewrite_page_links(clean_page(sources[name]), name, local)
        if not re.match(r"^#{1,3} ", body):
            body = f"## {title}\n\n{body}"
        out[name] = ORIGIN.format(what=f"{IG_REPO}@{IG_COMMIT[:7]} input/pagecontent/{name}") + body
    rows = "\n".join(f"| [{name}]({name}) | {title} | {_headings(out[name])} |"
                     for name, title in PAGES)
    out["README.md"] = (
        f"# CMS FHIR Quality Measure Development IG ({IG_VERSION}): Pages\n\n"
        f"The narrative pages of the IG, from [{IG_REPO}](https://github.com/{IG_REPO}/tree/"
        f"{IG_COMMIT}/input/pagecontent) at commit `{IG_COMMIT[:7]}` (the continuous build of "
        f"2026-11-03). Published at <{PUBLISHED}>. The IG declares its content CC0-1.0; the "
        "repository is Apache-2.0.\n\n"
        "| File | Page | Sections |\n| --- | --- | --- |\n" + rows + "\n")
    return out


def _headings(body: str) -> str:
    hs, fence = [], False
    for line in body.split("\n"):
        if line.lstrip().startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"^###? (.+)$", line)
        if m:
            hs.append(m.group(1).strip())
    return ", ".join(hs)[:300]


# --- Libraries ---------------------------------------------------------------------------------

def library_summary(cql: str) -> tuple[str, str, str]:
    """Return (version, models, includes) from a library's declarations."""
    m = re.search(r"^library\s+\S+\s+version\s+'([^']+)'", cql, flags=re.M)
    models = ", ".join(f"{n} {v}" for n, v in
                       re.findall(r"^using\s+(\S+)\s+version\s+'([^']+)'", cql, flags=re.M))
    includes = ", ".join(f"{n.rsplit('.', 1)[-1]} {v}" for n, v in
                         re.findall(r"^include\s+(\S+)\s+version\s+'([^']+)'", cql, flags=re.M))
    return (m.group(1) if m else ""), models, includes


def build_libraries(sources: dict[str, str]) -> dict[str, str]:
    out, rows = {}, []
    for lib in LIBRARIES:
        cql = sources[lib].replace("\r\n", "\n")
        out[f"{lib}.cql"] = cql if cql.endswith("\n") else cql + "\n"
        version, models, includes = library_summary(cql)
        rows.append(f"| [{lib}.cql]({lib}.cql) | {version} | {models} | {includes or '(none)'} | "
                    f"{out[lib + '.cql'].count(chr(10))} |")
    out["README.md"] = (
        f"# CMS FHIR Quality Measure Development IG ({IG_VERSION}): Libraries\n\n"
        f"The shared CQL libraries in [{IG_REPO}](https://github.com/{IG_REPO}/tree/{IG_COMMIT}/"
        "input/cql), as written. CQMCommon is being refactored into CQMConcepts, CQMElements and "
        "CQMInferences; see [../pages/refactored_index.md](../pages/refactored_index.md). "
        "FHIRHelpers and FHIRCommon come from the `cql-ig` skill, USCoreCommon and USCoreElements "
        "from `us-cql-ig`, and the USQualityCore model from `usqualitycore`.\n\n"
        "| File | Version | Models | Includes | Lines |\n| --- | --- | --- | --- | --- |\n"
        + "\n".join(rows) + "\n")
    return out


# --- Main --------------------------------------------------------------------------------------

def _fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as resp:
        return resp.read().decode("utf-8")


def read_sources(source_dir: Path | None) -> tuple[dict[str, str], dict[str, str]]:
    pages, libs = {}, {}
    for name, _ in PAGES:
        pages[name] = ((source_dir / "pages" / name).read_text(encoding="utf-8") if source_dir
                       else _fetch(RAW + "pagecontent/" + name))
    for lib in LIBRARIES:
        libs[lib] = ((source_dir / "cql" / f"{lib}.cql").read_text(encoding="utf-8") if source_dir
                     else _fetch(RAW + f"cql/{lib}.cql"))
    return pages, libs


def build(pages: dict[str, str], libs: dict[str, str]) -> dict[str, str]:
    """Return {path relative to resources/: content}."""
    out = {f"pages/{k}": v for k, v in build_pages(pages).items()}
    out.update({f"libraries/{k}": v for k, v in build_libraries(libs).items()})
    return out


def write(files: dict[str, str]) -> None:
    for folder in ("pages", "libraries"):
        target = RES / folder
        if target.exists():
            for old in sorted(target.rglob("*"), reverse=True):
                if old.is_file():
                    old.unlink()
                else:
                    try:
                        old.rmdir()
                    except OSError:  # held open (e.g. by an editor); it is reused below
                        pass
    for rel, body in files.items():
        path = RES / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source-dir", type=Path,
                        help="folder with pages/*.md and cql/*.cql from the IG's input/ folder")
    args = parser.parse_args(argv[1:])
    files = build(*read_sources(args.source_dir))
    write(files)
    print(f"Wrote {len(files)} files under {RES}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
