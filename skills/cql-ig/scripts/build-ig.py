#!/usr/bin/env python3
"""Regenerate the committed reference files from the Using CQL With FHIR IG.

Usage:
    python build-ig.py [--package-dir DIR] [--pages-dir DIR]

Without options, downloads the hl7.fhir.uv.cql package from packages.fhir.org and the IG's
narrative pages from HL7/cql-ig, both at the pinned versions below. The options read them from
local folders instead (an extracted package folder, and a folder of the pages' .md files), for
offline use and tests.

Writes, under resources/:
- pages/       the IG's narrative pages, with publisher markup removed and links rewritten
- libraries/   the CQL source of FHIRHelpers, FHIRCommon and their test libraries, as published
- modelinfo/   the FHIR ModelInfo, condensed to Markdown: contexts, conversions and every type

The IG and its package are published by HL7 under CC0-1.0. The output is committed, so run this
only when you change the pins or this script. Requires Python 3.9+, no packages.
"""
from __future__ import annotations

import argparse
import base64
import html
import io
import json
import re
import sys
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

IG_VERSION = "2.0.0"
PACKAGE = "hl7.fhir.uv.cql"
PACKAGE_URL = f"https://packages.fhir.org/{PACKAGE}/{IG_VERSION}"
IG_COMMIT = "24c4c3157d33760b1ee4b9f2edf64c7ceace65b6"  # HL7/cql-ig tag 2.0.0
PAGES_URL = f"https://raw.githubusercontent.com/HL7/cql-ig/{IG_COMMIT}/input/pages/"
PUBLISHED = "https://hl7.org/fhir/uv/cql/STU2/"
FHIR_R4 = "http://hl7.org/fhir/R4/"
# The extensions pack version the IG depends on (package.json: hl7.fhir.uv.extensions.r4 5.2.0).
EXTENSIONS = "http://hl7.org/fhir/extensions/5.2.0"

PAGES = [  # (file, title), in the IG's menu order
    ("index.md", "Home"),
    ("using-cql.md", "Using CQL"),
    ("patterns.md", "Patterns"),
    ("fhir-modelinfo.md", "FHIR ModelInfo"),
    ("conformance.md", "Conformance"),
    ("using-elm.md", "Using ELM"),
    ("using-modelinfo.md", "Using ModelInfo"),
    ("profiles.md", "Profiles"),
    ("extensions.md", "Extensions"),
    ("operations.md", "Operations"),
    ("changes.md", "Changes"),
]
LIBRARIES = ["FHIRHelpers", "FHIRCommon", "FHIRHelpersTests", "FHIRCommonTests"]
MODELINFO_LIBRARY = "FHIR-ModelInfo"

SKILL = Path(__file__).resolve().parent.parent
RES = SKILL / "resources"
MI = "{urn:hl7-org:elm-modelinfo:r1}"
XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"
ORIGIN = ("<!-- Generated by scripts/build-ig.py from {what} (CC0-1.0). Do not edit. -->\n\n")


# --- Pages -------------------------------------------------------------------------------------

def html_table_to_markdown(table: str) -> str:
    rows = re.findall(r"<tr>(.*?)</tr>", table, flags=re.S)
    out = []
    for i, row in enumerate(rows):
        cells = re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", row, flags=re.S)
        cells = [inline_html(c).replace("|", "\\|") for c in cells]
        out.append("| " + " | ".join(cells) + " |")
        if i == 0:
            out.append("|" + " --- |" * len(cells))
    return "\n".join(out)


def inline_html(text: str) -> str:
    text = re.sub(r"<a class=\"fmm\"[^>]*>(.*?)</a>", r"\1", text, flags=re.S)  # maturity level
    text = re.sub(r"<a\b[^>]*?href=\"([^\"]*)\"[^>]*>(.*?)</a>", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"</?p>", " ", text)
    text = re.sub(r"<code>(.*?)</code>", r"`\1`", text, flags=re.S)
    text = re.sub(r"<br\s*/?>", " ", text)
    text = re.sub(r"\s+", " ", text)
    return html.unescape(text).strip()


def clean_page(text: str) -> str:
    text = text.replace("\r\n", "\n")
    text = text.replace("{{site.data.fhir.path}}", FHIR_R4)
    text = text.replace("{{site.data.fhir.ver.ext}}", EXTENSIONS)
    # Tables the publisher generates from the package; the KB and this skill's indexes cover them.
    text = re.sub(r"\{%\s*include (\S+)\s*%\}",
                  lambda m: f"*(The published page has a generated table here: {m.group(1)}.)*",
                  text)
    text = re.sub(r"^\{:[^}]*\}\n?", "", text, flags=re.M)
    # Self-links on conformance requirements: [<img src="conformance.png" .../>](#anchor)
    text = re.sub(r"\s*\[<img [^>]*/>\]\(#[^)]*\)", "", text)
    text = re.sub(r"<img [^>]*/?>", "", text)
    text = re.sub(r"<table[^>]*>.*?</table>",
                  lambda m: "\n\n" + html_table_to_markdown(m.group(0)) + "\n\n", text, flags=re.S)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def link_target(page: str, anchor: str, local: dict[str, str]) -> str:
    suffix = f"#{anchor}" if anchor else ""
    if page in local:
        return local[page] + suffix
    return PUBLISHED + page + suffix


def rewrite_page_links(text: str, here: str, local: dict[str, str]) -> str:
    def repl(m):
        page, anchor = m.group(1), m.group(2) or ""
        if anchor and local.get(page) == here:
            return f"](#{anchor})"
        return f"]({link_target(page, anchor, local)})"
    return re.sub(r"\]\(([A-Za-z0-9_.-]+\.html)(?:#([^)\s]+))?\)", repl, text)


def build_pages(sources: dict[str, str]) -> dict[str, str]:
    local = {name.replace(".md", ".html"): name for name, _ in PAGES}
    local.update({f"Library-{lib}.html": f"../libraries/{lib}.cql" for lib in LIBRARIES})
    local[f"Library-{MODELINFO_LIBRARY}.html"] = "../modelinfo/README.md"
    out = {}
    for name, title in PAGES:
        body = clean_page(sources[name])
        if name == "fhir-modelinfo.md":  # the source table has no header row
            body = body.replace("\n\n|---|---|\n", "\n\n|Class|Primary Code Path|\n|---|---|\n", 1)
        body = rewrite_page_links(body, name, local)
        if not re.match(r"^#{1,3} ", body):
            body = f"## {title}\n\n{body}"
        out[name] = ORIGIN.format(
            what=f"HL7/cql-ig@{IG_COMMIT[:7]} input/pages/{name}") + body
    rows = "\n".join(f"| [{name}]({name}) | {title} | {_headings(out[name])} |"
                     for name, title in PAGES)
    out["README.md"] = (
        f"# Using CQL With FHIR {IG_VERSION}: Pages\n\n"
        f"The narrative pages of the IG, from [HL7/cql-ig](https://github.com/HL7/cql-ig/tree/"
        f"{IG_COMMIT}/input/pages) at tag {IG_VERSION} (CC0-1.0). Published at <{PUBLISHED}>. "
        "Links to artifact pages go to the published IG; build the local knowledge base "
        "(`scripts/build-kb.sh`) to read those artifacts offline.\n\n"
        "| File | Page | Sections |\n| --- | --- | --- |\n" + rows + "\n")
    return out


def _headings(body: str) -> str:
    hs, fence = [], False
    for line in body.split("\n"):
        if line.lstrip().startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"^###? (.+)$", line)
        if m:
            hs.append(m.group(1).strip())
    return ", ".join(hs)[:300]


# --- Libraries ---------------------------------------------------------------------------------

def content_of(library: dict, content_type: str) -> str:
    for c in library.get("content") or []:
        if c.get("contentType") == content_type and c.get("data"):
            return base64.b64decode(c["data"]).decode("utf-8")
    raise SystemExit(f"Library {library.get('id')} has no {content_type} content")


def build_libraries(package: dict[str, dict]) -> dict[str, str]:
    out, rows = {}, []
    for lib in LIBRARIES:
        res = package[f"Library-{lib}.json"]
        cql = content_of(res, "text/cql").replace("\r\n", "\n")
        out[f"{lib}.cql"] = cql if cql.endswith("\n") else cql + "\n"
        deps = ", ".join(r["resource"].rsplit("/", 1)[-1] for r in res.get("relatedArtifact") or []
                         if r.get("type") == "depends-on" and "/Library/" in r.get("resource", ""))
        rows.append(f"| [{lib}.cql]({lib}.cql) | `{res['url']}` | {res.get('version')} | "
                    f"{deps or '(none)'} | {out[lib + '.cql'].count(chr(10))} |")
    out["README.md"] = (
        f"# Using CQL With FHIR {IG_VERSION}: Libraries\n\n"
        f"The CQL source of the libraries published in the `{PACKAGE}` {IG_VERSION} package "
        "(CC0-1.0), taken from each Library resource's `text/cql` content. The package also "
        "carries their ELM (XML and JSON), which isn't copied here.\n\n"
        "| File | Canonical URL | Version | Depends on | Lines |\n"
        "| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n\n"
        "Note that FHIRHelpers has version 4.0.1 (it tracks the FHIR version), while FHIRCommon and "
        f"the test libraries have the IG version, {IG_VERSION}.\n")
    return out


# --- ModelInfo ---------------------------------------------------------------------------------

def type_spec(node) -> str:
    """Render an element's type: FHIR.string, List<FHIR.Identifier>, Choice<...>."""
    if node.get("elementType"):
        return node.get("elementType")
    spec = node.find(MI + "elementTypeSpecifier")
    if spec is None:
        spec = node.find(MI + "typeSpecifier")
    return specifier(spec) if spec is not None else "?"


def specifier(spec) -> str:
    kind = spec.get(XSI_TYPE, "")
    if kind == "ListTypeSpecifier":
        inner = spec.get("elementType")
        if not inner:
            child = spec.find(MI + "elementTypeSpecifier")
            inner = specifier(child) if child is not None else "?"
        return f"List<{inner}>"
    if kind == "ChoiceTypeSpecifier":
        choices = [specifier(c) for c in spec.findall(MI + "choice")]
        return "Choice<" + ", ".join(choices) + ">"
    if kind == "NamedTypeSpecifier":
        return f"{spec.get('namespace')}.{spec.get('name')}"
    return "?"


def build_modelinfo(xml_text: str) -> dict[str, str]:
    root = ET.fromstring(xml_text)
    types = {t.get("name"): t for t in root.findall(MI + "typeInfo")}
    top = sorted(n for n in types if "." not in n)
    resources = [n for n in top if _is_resource(types, n)]
    datatypes = [n for n in top if n not in resources and not _is_value_wrapper(types[n])]
    wrappers = [n for n in top if _is_value_wrapper(types[n])]
    out: dict[str, str] = {}

    def type_block(name: str, level: str) -> list[str]:
        t = types[name]
        lines = [f"{level} {t.get('namespace')}.{name}", ""]
        meta = [f"**Base:** `{t.get('baseType')}`"]
        if t.get("identifier"):
            meta.append(f"**Identifier:** `{t.get('identifier')}`")
        if t.get("retrievable") == "true":
            meta.append("**Retrievable:** yes")
        if t.get("primaryCodePath"):
            meta.append(f"**Primary code path:** `{t.get('primaryCodePath')}`")
        lines += [" | ".join(meta), ""]
        rels = [f"{r.get('context')} via `{r.get('relatedKeyElement')}`"
                for r in t.findall(MI + "contextRelationship")]
        if rels:
            lines += [f"**Context relationships:** {'; '.join(rels)}", ""]
        elements = t.findall(MI + "element")
        if elements:
            lines += ["| Element | Type |", "| --- | --- |"]
            lines += [f"| {e.get('name')} | `{type_spec(e)}` |" for e in elements]
            lines.append("")
        return lines

    def nested(name: str) -> list[str]:
        return sorted(n for n in types if n.startswith(name + "."))

    origin = ORIGIN.format(what=f"the FHIR-ModelInfo Library in {PACKAGE} {IG_VERSION}")
    for name in resources:
        lines = type_block(name, "#")
        for sub in nested(name):
            lines += type_block(sub, "##")
        out[f"resources/{name}.md"] = origin + "\n".join(lines).rstrip() + "\n"

    lines = ["# FHIR ModelInfo: Data Types", "",
             "Complex data types and their nested types. Primitive and code types are in "
             "[primitives.md](primitives.md).", ""]
    for name in datatypes:
        lines += type_block(name, "##")
        for sub in nested(name):
            lines += type_block(sub, "###")
    out["datatypes.md"] = origin + "\n".join(lines).rstrip() + "\n"

    lines = ["# FHIR ModelInfo: Primitive and Code Types", "",
             "Each of these types wraps one `value` element of a System type. FHIR primitives are "
             "the lowercase names. The capitalized names are the code types the model generates "
             "for required bindings (for example `FHIR.ObservationStatus`), each a "
             "`FHIR.Element` with a `System.String` value. FHIRHelpers converts each of them to "
             "its System type (see [conversions.md](conversions.md)).", "",
             "| Type | Base | Value type |", "| --- | --- | --- |"]
    for name in wrappers:
        t = types[name]
        value = t.find(MI + "element")
        lines.append(f"| FHIR.{name} | `{t.get('baseType')}` | `{type_spec(value)}` |")
    out["primitives.md"] = origin + "\n".join(lines) + "\n"

    conv = root.findall(MI + "conversionInfo")
    lines = ["# FHIR ModelInfo: Implicit Conversions", "",
             "When a FHIR-typed value is used where a System type is expected, the translator "
             "inserts a call to the conversion function listed here. These are the FHIRHelpers "
             "functions; see [FHIRHelpers.cql](../libraries/FHIRHelpers.cql).", "",
             "| From | To | Function |", "| --- | --- | --- |"]
    lines += [f"| `{c.get('fromType')}` | `{c.get('toType')}` | `{c.get('functionName')}` |"
              for c in conv]
    out["conversions.md"] = origin + "\n".join(lines) + "\n"

    contexts = root.findall(MI + "contextInfo")
    ctx_rows = [f"| {c.get('name')} | `{c.find(MI + 'contextType').get('namespace')}."
                f"{c.find(MI + 'contextType').get('name')}` | `{c.get('keyElement')}` | "
                f"{('`' + c.get('birthDateElement') + '`') if c.get('birthDateElement') else ''} |"
                for c in contexts]
    res_rows = []
    for name in resources:
        t = types[name]
        rels = ", ".join(sorted({r.get("context") for r in t.findall(MI + "contextRelationship")}))
        res_rows.append(f"| [{name}](resources/{name}.md) | "
                        f"{'yes' if t.get('retrievable') == 'true' else 'no'} | "
                        f"{('`' + t.get('primaryCodePath') + '`') if t.get('primaryCodePath') else ''}"
                        f" | {rels} |")
    out["README.md"] = (
        origin + f"# FHIR ModelInfo {root.get('version')}\n\n"
        f"The CQL model for FHIR R4, published as the `{MODELINFO_LIBRARY}` Library in "
        f"`{PACKAGE}` {IG_VERSION} and condensed here from its XML. A CQL library uses it with "
        f"`using FHIR version '{root.get('version')}'`.\n\n"
        f"- **Model:** `{root.get('name')}`, URL `{root.get('url')}`, target qualifier "
        f"`{root.get('targetQualifier')}`\n"
        f"- **Patient class:** `{root.get('patientClassName')}`, birth date property "
        f"`{root.get('patientBirthDatePropertyName')}`\n"
        f"- **Types:** {len(types)} ({len(resources)} resources, {len(datatypes)} data types, "
        f"{len(wrappers)} primitive and code types, and their nested backbone types)\n\n"
        "Files:\n\n"
        "- `resources/{Resource}.md`: each resource's elements and nested types\n"
        "- [datatypes.md](datatypes.md): complex data types\n"
        "- [primitives.md](primitives.md): primitive and code types and their System value types\n"
        "- [conversions.md](conversions.md): the implicit conversions to System types\n\n"
        "In element types, `List<T>` is a repeating element and `Choice<A, B>` a choice element "
        "(FHIR `value[x]`), which CQL addresses without the `[x]`, as `value`.\n\n"
        "## Contexts\n\n| Context | Type | Key element | Birth date element |\n"
        "| --- | --- | --- | --- |\n" + "\n".join(ctx_rows) + "\n\n"
        "## Resources\n\n"
        "A primary code path is the element a retrieve such as `[Condition: \"Diabetes\"]` filters "
        "on. Context relationships list the contexts from which a resource can be retrieved.\n\n"
        "| Resource | Retrievable | Primary code path | Context relationships |\n"
        "| --- | --- | --- | --- |\n" + "\n".join(res_rows) + "\n")
    return out


def _is_resource(types, name) -> bool:
    seen = set()
    while name and name not in seen:
        seen.add(name)
        if name == "Resource":
            return True
        base = types.get(name)
        if base is None:
            return False
        name = (base.get("baseType") or "").removeprefix("FHIR.")
    return False


def _is_value_wrapper(t) -> bool:
    elements = t.findall(MI + "element")
    return (len(elements) == 1 and elements[0].get("name") == "value" and
            (elements[0].get("elementType") or "").startswith("System."))


# --- Main --------------------------------------------------------------------------------------

def read_package(package_dir: Path | None) -> dict[str, dict]:
    wanted = {f"Library-{n}.json" for n in LIBRARIES + [MODELINFO_LIBRARY]}
    found: dict[str, dict] = {}
    if package_dir:
        for name in wanted:
            found[name] = json.loads((package_dir / name).read_text(encoding="utf-8"))
        return found
    with urllib.request.urlopen(PACKAGE_URL, timeout=120) as resp:
        data = resp.read()
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            base = member.name.rsplit("/", 1)[-1]
            if member.name == f"package/{base}" and base in wanted:
                found[base] = json.loads(tar.extractfile(member).read().decode("utf-8"))
    missing = wanted - set(found)
    if missing:
        raise SystemExit(f"package is missing {sorted(missing)}")
    return found


def read_pages(pages_dir: Path | None) -> dict[str, str]:
    pages = {}
    for name, _ in PAGES:
        if pages_dir:
            pages[name] = (pages_dir / name).read_text(encoding="utf-8")
        else:
            with urllib.request.urlopen(PAGES_URL + name, timeout=60) as resp:
                pages[name] = resp.read().decode("utf-8")
    return pages


def build(package: dict[str, dict], pages: dict[str, str]) -> dict[str, str]:
    """Return {path relative to resources/: content}."""
    out = {}
    out.update({f"pages/{k}": v for k, v in build_pages(pages).items()})
    out.update({f"libraries/{k}": v for k, v in build_libraries(package).items()})
    mi_xml = content_of(package[f"Library-{MODELINFO_LIBRARY}.json"], "application/xml")
    out.update({f"modelinfo/{k}": v for k, v in build_modelinfo(mi_xml).items()})
    return out


def write(files: dict[str, str]) -> None:
    for folder in ("pages", "libraries", "modelinfo"):
        target = RES / folder
        if target.exists():
            for old in sorted(target.rglob("*"), reverse=True):
                if old.is_file():
                    old.unlink()
                else:
                    try:
                        old.rmdir()
                    except OSError:  # held open (e.g. by an editor); it is reused below
                        pass
    for rel, body in files.items():
        path = RES / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--package-dir", type=Path, help="extracted package/ folder")
    parser.add_argument("--pages-dir", type=Path, help="folder of the IG's input/pages .md files")
    args = parser.parse_args(argv[1:])
    files = build(read_package(args.package_dir), read_pages(args.pages_dir))
    write(files)
    print(f"Wrote {len(files)} files under {RES}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
