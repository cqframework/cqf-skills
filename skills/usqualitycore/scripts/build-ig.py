#!/usr/bin/env python3
"""Regenerate the committed reference files from the US Quality Core IG.

Usage:
    python build-ig.py [--package-dir DIR] [--pages-dir DIR]

Without options, downloads the fhir.onc.us-quality-core package from packages.fhir.org and the
IG's narrative pages (and the .md files they include) from FHIR/us-quality-core, both at the pinned
versions below. The options read them from local folders instead (an extracted package folder, and
a folder holding the pages' .md files with an includes/ subfolder), for offline use and tests.

Writes, under resources/:
- pages/       the IG's narrative pages, with publisher markup removed and links rewritten
- libraries/   the CQL source of USQualityCoreCommon and its tests
- modelinfo/   the USQualityCore ModelInfo (0.5.0), condensed to Markdown

The IG and its package are published under CC0-1.0. The output is committed, so run this only when
you change the pins or this script. Requires Python 3.9+, no packages.
"""
from __future__ import annotations

import argparse
import base64
import html
import io
import json
import re
import sys
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

IG_VERSION = "0.5.0"
PACKAGE = "fhir.onc.us-quality-core"
PACKAGE_URL = f"https://packages.fhir.org/{PACKAGE}/{IG_VERSION}"
IG_REPO = "FHIR/us-quality-core"
IG_COMMIT = "8c88981db0653bed2ab7c38d6908525f47ac77bb"  # the 0.5.0 release
PAGES_URL = f"https://raw.githubusercontent.com/{IG_REPO}/{IG_COMMIT}/input/pages/"
INCLUDES_URL = f"https://raw.githubusercontent.com/{IG_REPO}/{IG_COMMIT}/input/includes/"
PUBLISHED = "https://fhir.org/guides/onc/us-quality-core/0.5.0/"
# Where the publisher's {{site.data.fhir.ver.X}} variables point, from input/us-quality-core.xml.
DEPENDENCIES = {"uscore": "http://hl7.org/fhir/us/core/STU6.1"}
FHIR_R4 = "http://hl7.org/fhir/R4/"

PAGES = [  # (file, title), in the IG's menu order
    ("index.md", "Home"),
    ("conformance.md", "Conformance"),
    ("general-requirements.md", "General Requirements"),
    ("must-support.md", "Must Support"),
    ("security.md", "Privacy, Security, and Consent"),
    ("guidance.md", "Guidance"),
    ("uscdiquality.md", "USCDI+ Quality"),
    ("negation.md", "US Quality Core Negation"),
    ("provenance.md", "Provenance"),
    ("relationship-with-uscore-qicore.md", "Relationship with US Core and QI-Core"),
    ("qdm-to-us-quality-core.md", "QDM 5.6 to US Quality Core 0.5.0 Mapping"),
    ("capability-statements.md", "Capability Statements"),
    ("profiles.md", "Profiles"),
    ("extensions.md", "Extensions"),
    ("terminology.md", "Terminology"),
    ("examples.md", "Examples"),
    ("cql-artifacts.md", "CQL Artifacts and Patterns (Informational)"),
    ("modelinfo.md", "US Quality Core ModelInfo (Informational)"),
    ("patterns.md", "US Quality Core Patterns (Informational)"),
    ("downloads.md", "Downloads"),
    ("changes.md", "Change Log"),
]
LIBRARIES = ["USQualityCoreCommon", "USQualityCoreCommonTests"]
MODELINFO_LIBRARY = "USQualityCore-ModelInfo"

SKILL = Path(__file__).resolve().parent.parent
RES = SKILL / "resources"
MI = "{urn:hl7-org:elm-modelinfo:r1}"
XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"
ORIGIN = "<!-- Generated by scripts/build-ig.py from {what} (CC0-1.0). Do not edit. -->\n\n"
INCLUDE_MD = r"\{%\s*include ([\w.-]+\.md)\s*%\}"


# --- Pages -------------------------------------------------------------------------------------

def html_table_to_markdown(table: str) -> str:
    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", table, flags=re.S)
    out = []
    for i, row in enumerate(rows):
        cells = re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", row, flags=re.S)
        cells = [inline_html(c).replace("|", "\\|") for c in cells]
        out.append("| " + " | ".join(cells) + " |")
        if i == 0:
            out.append("|" + " --- |" * len(cells))
    return "\n".join(out)


def inline_html(text: str) -> str:
    text = re.sub(r"<a\b[^>]*?href=\"([^\"]*)\"[^>]*>(.*?)</a>", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"</?p>", " ", text)
    text = re.sub(r"<code>(.*?)</code>", r"`\1`", text, flags=re.S)
    text = re.sub(r"<br\s*/?>", " ", text)
    text = re.sub(r"\s+", " ", text)
    return html.unescape(text).strip()


def inline_includes(text: str, includes: dict[str, str]) -> str:
    """Replace {% include x.md %} with that file's text (the IG nests them one level deep)."""
    return re.sub(INCLUDE_MD, lambda m: includes[m.group(1)].strip(), text)


def clean_page(text: str) -> str:
    text = text.replace("\r\n", "\n")
    text = text.replace("{{site.data.fhir.path}}", FHIR_R4)
    for key, url in DEPENDENCIES.items():
        text = text.replace("{{site.data.fhir.ver." + key + "}}", url)
    text = re.sub(r"\{%\s*include img[\w-]*\.html[^%]*%\}", "", text)
    # Tables the publisher generates from the package; the knowledge base covers them.
    text = re.sub(r"\{%\s*(?:include|lang-fragment) (\S+)\s*%\}",
                  lambda m: f"*(The published page has a generated table here: {m.group(1)}.)*",
                  text)
    text = re.sub(r"^\{:[^}]*\}\n?", "", text, flags=re.M)
    text = re.sub(r"<img [^>]*/?>", "", text)
    text = re.sub(r"<table[^>]*>.*?</table>",
                  lambda m: "\n\n" + html_table_to_markdown(m.group(0)) + "\n\n", text, flags=re.S)
    text = re.sub(r"[ \t]*<li>\s*(.*?)\s*</li>\s*", lambda m: "- " + inline_html(m.group(1)) + "\n",
                  text, flags=re.S)
    text = re.sub(r"[ \t]*</?ul>[ \t]*\n?", "", text)
    text = re.sub(r"<a\b[^>]*?href=\"([^\"]*)\"[^>]*>(.*?)</a>", r"[\2](\1)", text, flags=re.S)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def link_target(page: str, anchor: str, local: dict[str, str]) -> str:
    suffix = f"#{anchor}" if anchor else ""
    if page in local:
        return local[page] + suffix
    return PUBLISHED + page + suffix


def rewrite_page_links(text: str, here: str, local: dict[str, str]) -> str:
    def repl(m):
        page, anchor = m.group(1), m.group(2) or ""
        if anchor and local.get(page) == here:
            return f"](#{anchor})"
        return f"]({link_target(page, anchor, local)})"
    return re.sub(r"\]\(([A-Za-z0-9_.-]+\.html)(?:#([^)\s]+))?\)", repl, text)


def build_pages(sources: dict[str, str], includes: dict[str, str]) -> dict[str, str]:
    local = {name.replace(".md", ".html"): name for name, _ in PAGES}
    local.update({f"Library-{lib}.html": f"../libraries/{lib}.cql" for lib in LIBRARIES})
    local[f"Library-{MODELINFO_LIBRARY}.html"] = "../modelinfo/README.md"
    out = {}
    for name, title in PAGES:
        body = clean_page(inline_includes(sources[name], includes))
        body = rewrite_page_links(body, name, local)
        if not re.match(r"^#{1,3} ", body):
            body = f"## {title}\n\n{body}"
        out[name] = ORIGIN.format(what=f"{IG_REPO}@{IG_COMMIT[:7]} input/pages/{name}") + body
    rows = "\n".join(f"| [{name}]({name}) | {title} | {_headings(out[name])} |"
                     for name, title in PAGES)
    out["README.md"] = (
        f"# US Quality Core {IG_VERSION}: Pages\n\n"
        f"The narrative pages of the IG, from [{IG_REPO}](https://github.com/{IG_REPO}/tree/"
        f"{IG_COMMIT}/input/pages) at the {IG_VERSION} release (CC0-1.0). Published at "
        f"<{PUBLISHED}>. Links to the IG's artifact pages go to the published IG; the profiles "
        "themselves are in the local knowledge base (`scripts/build-kb.sh`).\n\n"
        "| File | Page | Sections |\n| --- | --- | --- |\n" + rows + "\n")
    return out


def _headings(body: str) -> str:
    hs, fence = [], False
    for line in body.split("\n"):
        if line.lstrip().startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"^###? (.+)$", line)
        if m:
            hs.append(m.group(1).strip())
    return ", ".join(hs)[:300]


# --- Libraries ---------------------------------------------------------------------------------

def content_of(library: dict, content_type: str) -> str:
    for c in library.get("content") or []:
        if str(c.get("contentType", "")).split(";")[0].strip() == content_type and c.get("data"):
            return base64.b64decode(c["data"]).decode("utf-8")
    raise SystemExit(f"Library {library.get('id')} has no {content_type} content")


def build_libraries(package: dict[str, dict]) -> dict[str, str]:
    out, rows = {}, []
    for lib in LIBRARIES:
        res = package[f"Library-{lib}.json"]
        cql = content_of(res, "text/cql").replace("\r\n", "\n")
        out[f"{lib}.cql"] = cql if cql.endswith("\n") else cql + "\n"
        deps = ", ".join(r["resource"].rsplit("/", 1)[-1] for r in res.get("relatedArtifact") or []
                         if r.get("type") == "depends-on" and "/Library/" in r.get("resource", ""))
        rows.append(f"| [{lib}.cql]({lib}.cql) | `{res['url']}` | {res.get('version')} | "
                    f"{deps or '(none)'} | {out[lib + '.cql'].count(chr(10))} |")
    model = package[f"Library-{MODELINFO_LIBRARY}.json"]
    out["README.md"] = (
        f"# US Quality Core {IG_VERSION}: Libraries\n\n"
        f"The CQL source of the libraries published in the `{PACKAGE}` {IG_VERSION} package "
        "(CC0-1.0), taken from each Library resource's `text/cql` content. The package also "
        "carries their ELM, which isn't copied here. FHIRHelpers and FHIRCommon come from the "
        "Using CQL With FHIR IG (see the `cql-ig` skill), and USCoreCommon and USCoreElements "
        "from the US CQL IG (see the `us-cql-ig` skill).\n\n"
        "| File | Canonical URL | Version | Depends on | Lines |\n"
        "| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n\n"
        f"The model definition, `{model['url']}` version {model.get('version')}, is condensed in "
        "[../modelinfo/README.md](../modelinfo/README.md).\n")
    return out


# --- ModelInfo ---------------------------------------------------------------------------------

def type_spec(node) -> str:
    """Render an element's type: FHIR.string, List<FHIR.Identifier>, Choice<...>."""
    if node.get("elementType"):
        return node.get("elementType")
    spec = node.find(MI + "elementTypeSpecifier")
    if spec is None:
        spec = node.find(MI + "typeSpecifier")
    return specifier(spec) if spec is not None else "?"


def specifier(spec) -> str:
    kind = spec.get(XSI_TYPE, "")
    if kind == "ListTypeSpecifier":
        inner = spec.get("elementType")
        if not inner:
            child = spec.find(MI + "elementTypeSpecifier")
            inner = specifier(child) if child is not None else "?"
        return f"List<{inner}>"
    if kind == "ChoiceTypeSpecifier":
        return "Choice<" + ", ".join(specifier(c) for c in spec.findall(MI + "choice")) + ">"
    if kind == "NamedTypeSpecifier":
        return f"{spec.get('namespace')}.{spec.get('name')}"
    return "?"


def build_modelinfo(xml_text: str) -> dict[str, str]:
    root = ET.fromstring(xml_text)
    model = root.get("name")
    types = {t.get("name"): t for t in root.findall(MI + "typeInfo")}
    top = sorted(n for n in types if "." not in n)
    origin = ORIGIN.format(what=f"the {MODELINFO_LIBRARY} Library in {PACKAGE} {IG_VERSION}")
    out: dict[str, str] = {}

    def block(name: str, level: str) -> list[str]:
        t = types[name]
        lines = [f"{level} {t.get('namespace')}.{name}", ""]
        meta = [f"**Base:** `{t.get('baseType')}`"]
        if t.get("label"):
            meta.append(f"**Label:** \"{t.get('label')}\"")
        if t.get("identifier"):
            meta.append(f"**Profile:** `{t.get('identifier')}`")
        meta.append(f"**Retrievable:** {'yes' if t.get('retrievable') == 'true' else 'no'}")
        if t.get("primaryCodePath"):
            meta.append(f"**Primary code path:** `{t.get('primaryCodePath')}`")
        lines += [" | ".join(meta), ""]
        elements = t.findall(MI + "element")
        if elements:
            lines += ["| Element | Type |", "| --- | --- |"]
            lines += [f"| {e.get('name')} | `{type_spec(e)}` |" for e in elements]
            lines.append("")
        return lines

    rows = []
    for name in top:
        t = types[name]
        lines = block(name, "#")
        for sub in sorted(n for n in types if n.startswith(name + ".")):
            lines += block(sub, "##")
        out[f"classes/{name}.md"] = origin + "\n".join(lines).rstrip() + "\n"
        rows.append(
            f"| [{name}](classes/{name}.md) | {t.get('label') or ''} | `{t.get('baseType')}` | "
            f"{'yes' if t.get('retrievable') == 'true' else 'no'} | "
            f"{('`' + t.get('primaryCodePath') + '`') if t.get('primaryCodePath') else ''} |")
    required = ", ".join(f"{r.get('name')} {r.get('version')}"
                         for r in root.findall(MI + "requiredModelInfo"))
    contexts = "; ".join(f"{c.get('name')} (`{c.find(MI + 'contextType').get('namespace')}."
                         f"{c.find(MI + 'contextType').get('name')}`, key `{c.get('keyElement')}`)"
                         for c in root.findall(MI + "contextInfo"))
    out["README.md"] = (
        origin + f"# {model} ModelInfo {root.get('version')}\n\n"
        f"The CQL model of the US Quality Core {root.get('version')} profiles, published as the "
        f"`{MODELINFO_LIBRARY}` Library in `{PACKAGE}` {IG_VERSION} and condensed here from its "
        f"XML. A library uses it with `using {model} version '{root.get('version')}'`.\n\n"
        f"- **Model:** `{model}`, URL `{root.get('url')}`, target `{root.get('targetUrl')}`, "
        f"qualifier `{root.get('targetQualifier')}`\n"
        f"- **Requires:** {required}. This is a derived model: each class extends a USCore or "
        "FHIR class, so FHIR types, the FHIRHelpers conversions and the US Core libraries "
        "apply.\n"
        f"- **Patient class:** `{model}.{root.get('patientClassName')}`, birth date property "
        f"`{root.get('patientBirthDatePropertyName')}`\n"
        f"- **Contexts:** {contexts}\n"
        f"- **Classes:** {len(top)}, plus {len(types) - len(top)} nested classes listed in their "
        "owner's file\n\n"
        "Retrieve a class by name or by its quoted label. Declare `using FHIR` too, because the "
        "FHIRHelpers conversions don't apply without it. Most class names are also FHIR type "
        f"names, so qualify them (`[{model}.Encounter]`): with `using FHIR` declared, the "
        "unqualified name resolves to the FHIR type. "
        "A class with no primary code path needs an explicit code path in a terminology "
        "retrieve. In element types, `List<T>` is a repeating element and `Choice<A, B>` a choice "
        "element.\n\n"
        "| Class | Label | Base | Retrievable | Primary code path |\n"
        "| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n")
    return out


# --- Main --------------------------------------------------------------------------------------

def _fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as resp:
        return resp.read().decode("utf-8")


def read_package(package_dir: Path | None) -> dict[str, dict]:
    wanted = {f"Library-{n}.json" for n in LIBRARIES + [MODELINFO_LIBRARY]}
    found: dict[str, dict] = {}
    if package_dir:
        for name in wanted:
            found[name] = json.loads((package_dir / name).read_text(encoding="utf-8"))
        return found
    with urllib.request.urlopen(PACKAGE_URL, timeout=120) as resp:
        data = resp.read()
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            base = member.name.rsplit("/", 1)[-1]
            if member.name == f"package/{base}" and base in wanted:
                found[base] = json.loads(tar.extractfile(member).read().decode("utf-8"))
    missing = wanted - set(found)
    if missing:
        raise SystemExit(f"package is missing {sorted(missing)}")
    return found


def read_pages(pages_dir: Path | None) -> tuple[dict[str, str], dict[str, str]]:
    pages, includes = {}, {}
    for name, _ in PAGES:
        pages[name] = ((pages_dir / name).read_text(encoding="utf-8") if pages_dir
                       else _fetch(PAGES_URL + name))
    for name in sorted({m for p in pages.values() for m in re.findall(INCLUDE_MD, p)}):
        includes[name] = ((pages_dir / "includes" / name).read_text(encoding="utf-8")
                          if pages_dir else _fetch(INCLUDES_URL + name))
    return pages, includes


def build(package: dict[str, dict], pages: dict[str, str],
          includes: dict[str, str] | None = None) -> dict[str, str]:
    """Return {path relative to resources/: content}."""
    out = {}
    out.update({f"pages/{k}": v for k, v in build_pages(pages, includes or {}).items()})
    out.update({f"libraries/{k}": v for k, v in build_libraries(package).items()})
    mi_xml = content_of(package[f"Library-{MODELINFO_LIBRARY}.json"], "application/xml")
    out.update({f"modelinfo/{k}": v for k, v in build_modelinfo(mi_xml).items()})
    return out


def write(files: dict[str, str]) -> None:
    for folder in ("pages", "libraries", "modelinfo"):
        target = RES / folder
        if target.exists():
            for old in sorted(target.rglob("*"), reverse=True):
                if old.is_file():
                    old.unlink()
                else:
                    try:
                        old.rmdir()
                    except OSError:  # held open (e.g. by an editor); it is reused below
                        pass
    for rel, body in files.items():
        path = RES / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--package-dir", type=Path, help="extracted package/ folder")
    parser.add_argument("--pages-dir", type=Path,
                        help="folder of the IG's input/pages .md files, with an includes/ subfolder")
    args = parser.parse_args(argv[1:])
    pages, includes = read_pages(args.pages_dir)
    files = build(read_package(args.package_dir), pages, includes)
    write(files)
    print(f"Wrote {len(files)} files under {RES}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
