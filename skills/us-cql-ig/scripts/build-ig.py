#!/usr/bin/env python3
"""Regenerate the committed reference files from the Common CQL Artifacts for FHIR (US-Based) IG.

Usage:
    python build-ig.py [--package-dir DIR] [--pages-dir DIR]

Without options, downloads the hl7.fhir.us.cql package from packages.fhir.org and the IG's
narrative pages from HL7/us-cql-ig, both at the pinned versions below. The options read them from
local folders instead (an extracted package folder, and a folder of the pages' .md files), for
offline use and tests.

Writes, under resources/:
- pages/       the IG's narrative pages, with publisher markup removed and links rewritten
- libraries/   the CQL source of USCoreCommon, USCoreElements and the IG's other libraries
- modelinfo/   the USCore ModelInfo (6.1.0-derived), condensed to Markdown

The IG and its package are published by HL7 under CC0-1.0. The output is committed, so run this
only when you change the pins or this script. Requires Python 3.9+, no packages.
"""
