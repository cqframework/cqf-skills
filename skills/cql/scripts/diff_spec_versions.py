#!/usr/bin/env python3
"""List the spec sections whose text differs between two split versions.

Usage:
    diff_spec_versions.py <spec-dir> <old-version> <new-version>

Sections are matched by page + heading path (file numbering shifts between
versions, so file names are not compared). Writes <spec-dir>/CHANGES-<old>-to-<new>.md.
"""

import difflib
import re
import sys
from pathlib import Path

META_RE = re.compile(r"^<!--\n(.*?)\n-->\n", re.S)

# Markup that differs between the AsciiDoc (1.4) and markdown (1.5+) sources but not in the
# rendered text. Removed before comparing, so the change list reflects wording, not format.
FORMAT_RULES = [
    (re.compile(r"^\s*(#{1,6}|={1,6})\s+"), ""),             # heading markers
    (re.compile(r"^\s*(```\w*|~~~|-{4,}|\.{4,}|\[source[^\]]*\]|\[cols[^\]]*\]|\[options[^\]]*\]|\|===)\s*$"), ""),
    (re.compile(r"^\s*\|?\s*(:?-{3,}:?\s*\|\s*)+:?-{3,}:?\s*\|?\s*$"), ""),  # md table rule
    (re.compile(r"^\s*={3,}\s*$"), ""),                       # adoc block/table delimiter
    (re.compile(r"^\s*_{4,}\s*$"), ""),                       # adoc quote block
    (re.compile(r"^\s*>\s?"), ""),                            # md blockquote
    (re.compile(r"\\([<>*_#\[\]])"), r"\1"),                  # md escapes
    (re.compile(r"^\s*\{:[^}]*\}\s*$"), ""),                   # kramdown attribute list
    (re.compile(r"^\s*\[\.?[\w .#-]*\]\s*$"), ""),             # adoc block attribute line
    (re.compile(r"image::?[^\[\s]+\[[^\]]*\]"), ""),           # adoc image
    (re.compile(r"!\[[^\]]*\]\([^)]*\)"), ""),                 # md image
    (re.compile(r"^\s*([*-]+|\d+\.)\s+"), ""),                 # list bullets
    (re.compile(r"link:[^\[\s]+\[([^\]]*)\]"), r"\1"),         # adoc link
    (re.compile(r"<<[^,>]+,([^>]*)>>"), r"\1"),                 # adoc xref with text
    (re.compile(r"<<([^>]+)>>"), r"\1"),
    (re.compile(r"\[([^\]]+)\]\([^)]*\)"), r"\1"),              # md link
    (re.compile(r"\*\*([^*]+)\*\*"), r"\1"),                    # md bold
    (re.compile(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])"), r"\1"),   # adoc bold / md italic
    (re.compile(r"(?<!\w)_([^_\n]+)_(?!\w)"), r"\1"),           # italic
    (re.compile(r"`([^`]+)`"), r"\1"),
    (re.compile(r"^(NOTE|TIP|IMPORTANT|WARNING|CAUTION):\s*"), "Note: "),
    (re.compile(r"\s*\|\s*"), " "),                             # table cell separators
    (re.compile(r"[’‘]"), "'"),
    (re.compile(r"[“”]"), '"'),
    (re.compile(r"[–—]"), "-"),
    (re.compile(r"\s+"), " "),
]


def normalize(text: str):
    out = []
    for line in text.splitlines():
        for rx, rep in FORMAT_RULES:
            line = rx.sub(rep, line)
        line = line.strip()
        if line:
            out.append(line)
    return out


def load(version_dir: Path):
    sections = {}
    for f in sorted((version_dir / "sections").rglob("*.md")):
        text = f.read_text(encoding="utf-8")
        m = META_RE.match(text)
        meta = dict(line.split(": ", 1) for line in m.group(1).splitlines())
        key = (meta["page"], meta["section"])
        sections[key] = (meta["url"], text[m.end():])
    return sections


def main():
    spec_dir, old, new = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    a, b = load(spec_dir / old), load(spec_dir / new)
    added = [k for k in b if k not in a]
    removed = [k for k in a if k not in b]
    changed = []
    for k in b:
        if k in a and normalize(a[k][1]) != normalize(b[k][1]):
            diff = list(difflib.unified_diff(
                normalize(a[k][1]), normalize(b[k][1]), lineterm="", n=0))
            plus = sum(1 for d in diff if d.startswith("+") and not d.startswith("+++"))
            minus = sum(1 for d in diff if d.startswith("-") and not d.startswith("---"))
            changed.append((k, plus, minus, diff))

    out = spec_dir / f"CHANGES-{old}-to-{new}.md"
    with out.open("w", encoding="utf-8") as fh:
        fh.write(f"# CQL specification changes: {old} to {new}\n\n")
        fh.write("Generated by `scripts/diff_spec_versions.py`. Sections matched by page and "
                 "heading path; a renamed heading shows as one removal plus one addition. Text is "
                 "compared after stripping source-format markup (AsciiDoc vs markdown), and diffs "
                 "show that normalized text, so quote from the section files, not from here.\n\n")
        fh.write(f"- Changed: {len(changed)}\n- Added: {len(added)}\n- Removed: {len(removed)}\n\n")
        fh.write("## Changed sections\n\n| Page | Section | +/- |\n| --- | --- | --- |\n")
        for (page, sec), plus, minus, _ in changed:
            fh.write(f"| {page} | [{sec.replace('|', '/')}]({b[(page, sec)][0]}) | +{plus} / -{minus} |\n")
        fh.write("\n## Added sections\n\n")
        for page, sec in added:
            fh.write(f"- {page}: [{sec}]({b[(page, sec)][0]})\n")
        fh.write("\n## Removed sections\n\n")
        for page, sec in removed:
            fh.write(f"- {page}: {sec}\n")
        fh.write("\n## Diffs\n")
        for (page, sec), _, _, diff in changed:
            fh.write(f"\n### {page}: {sec}\n\n```diff\n")
            fh.write("\n".join(d for d in diff if not d.startswith(("---", "+++"))) + "\n```\n")
    print(f"{len(changed)} changed, {len(added)} added, {len(removed)} removed -> {out}")


if __name__ == "__main__":
    main()
