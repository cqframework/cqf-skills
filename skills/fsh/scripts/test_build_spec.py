"""Tests for build-spec.py, run on a small synthetic source in the shape of the FSH spec."""
import importlib.util
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("build_spec", HERE / "build-spec.py")
bs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bs)

REFERENCE = """{%include styles.html%}

<br/>
<span style="background-color: LightYellow;">NOTE: Information on this page is normative content except where noted.</span>
<br/>

Trial-use parts are marked by {%include tu.html%}.

### Notational Conventions

<span class="caption" id="t1">Table 1. Syntax expressions</span>

| Style | Example |
|---|---|
| optional | <code><span class="optional">{flag}</span></code> |
{: .grid }

See [cardinality](#cardinality-rules), [Table 1](#t1) and the [overview](overview.html).

### FSH Rules

Rules intro.

#### Assignment Rules

<pre><code>* &lt;element&gt; = {value} <span class="optional">(exactly)</span></code></pre>

A [TU] feature: {%include tu-span.html%}`CodeableReference`</span> values.

#### Cardinality Rules

{%include tu-div.html%}
Trial-use paragraph.

```
* ^context = "x"
```
</div>

Back to [assignment](reference.html#assignment-rules) and the [change log](change_log.html).
"""

OVERVIEW = """{%include styles.html%}

### FHIR Shorthand Language Basics

See [indented rules](reference.html#cardinality-rules) and [the reference](reference.html).
"""


@pytest.fixture
def built(monkeypatch):
    monkeypatch.setattr(bs, "SPLIT_LINES", 10)
    return bs.build({"reference.md": REFERENCE, "overview.md": OVERVIEW})


def test_files_split_by_section(built):
    assert sorted(built) == [
        "01-notational-conventions.md", "02-rules-assignment.md", "03-rules-cardinality.md",
        "README.md", "overview.md"]


def test_preamble_opens_first_file_and_rules_intro_opens_first_rule(built):
    first = built["01-notational-conventions.md"]
    assert "> NOTE: Information on this page is normative" in first
    assert first.index("Trial-use parts are marked by [TU]") < first.index("### Notational")
    assert "### FSH Rules\n\nRules intro." in built["02-rules-assignment.md"]


def test_markup_removed(built):
    text = "\n".join(built.values())
    for leftover in ("{%", "<span", "</div>", "<pre>", "&lt;", "{: .grid }"):
        assert leftover not in text, leftover


def test_optional_and_trial_use_markers(built):
    assert "`«{flag}»`" in built["01-notational-conventions.md"]
    assignment = built["02-rules-assignment.md"]
    assert "```\n* <element> = {value} «(exactly)»\n```" in assignment
    assert "[TU] `CodeableReference` values." in assignment
    cardinality = built["03-rules-cardinality.md"]
    assert "> **[Trial Use]**\n>\n> Trial-use paragraph." in cardinality
    assert "> * ^context = \"x\"" in cardinality


def test_links_rewritten(built):
    conventions = built["01-notational-conventions.md"]
    assert "[cardinality](03-rules-cardinality.md#cardinality-rules)" in conventions
    assert "[Table 1](#t1)" in conventions
    assert "[overview](overview.md)" in conventions
    cardinality = built["03-rules-cardinality.md"]
    assert "[assignment](02-rules-assignment.md#assignment-rules)" in cardinality
    assert "[change log](https://hl7.org/fhir/uv/shorthand/change_log.html)" in cardinality
    overview = built["overview.md"]
    assert "(03-rules-cardinality.md#cardinality-rules)" in overview
    assert "[the reference](README.md)" in overview


def test_unknown_anchor_is_an_error(monkeypatch):
    monkeypatch.setattr(bs, "SPLIT_LINES", 10)
    with pytest.raises(SystemExit, match="#no-such-section"):
        bs.build({"reference.md": REFERENCE + "\n[x](#no-such-section)\n",
                  "overview.md": OVERVIEW})


def test_index_and_provenance(built):
    index = built["README.md"]
    assert f"FHIR Shorthand {bs.FSH_VERSION}" in index
    assert "| [02-rules-assignment.md](02-rules-assignment.md) | FSH Rules | Assignment Rules |" in index
    for name, body in built.items():
        if name != "README.md":
            assert body.startswith("<!-- Generated by scripts/build-spec.py"), name


def test_committed_spec_matches_index():
    spec = HERE.parent / "resources" / "spec"
    listed = set()
    for line in (spec / "README.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("| ["):
            listed.add(line.split("](")[1].split(")")[0])
    assert listed == {p.name for p in spec.glob("*.md")} - {"README.md"}
